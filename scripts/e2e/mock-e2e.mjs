// Drives the browser mock end to end in real Chromium. Exits non-zero on any failure.
// Needs `bun run dev --port 1420` running, and Playwright available to this script:
//   mkdir /tmp/e2e && cd /tmp/e2e && bun add playwright && bunx playwright install chromium-headless-shell
//   cp <repo>/scripts/e2e/mock-e2e.mjs . && SHOTS=/tmp/shots node mock-e2e.mjs
// This validates the UI against simulated data only. It says nothing about real targets.
import { chromium } from "playwright"
const SHOTS = process.env.SHOTS
const browser = await chromium.launch()
const ctx = await browser.newContext({ viewport: { width: 1440, height: 950 } })
await ctx.grantPermissions(["clipboard-read", "clipboard-write"], { origin: "http://localhost:1420" })
const page = await ctx.newPage()
const problems = []
page.on("pageerror", (e) => problems.push("pageerror: " + e.message))
page.on("console", (m) => { if (m.type() === "error") problems.push("console: " + m.text()) })
const shot = (n) => page.screenshot({ path: `${SHOTS}/${n}.png` })
const step = async (name, fn) => { try { await fn(); console.log("ok  ", name) } catch (e) { problems.push(`${name}: ${e.message.split("\n")[0]}`); console.log("FAIL", name, e.message.split("\n")[0]); await shot("fail-" + name.replace(/\W+/g, "-")) } }
const vis = (l) => l.first().waitFor({ state: "visible", timeout: 8000 })
await page.goto("http://localhost:1420")
const side = page.locator("aside"), main = page.locator("main")

await step("overview + markers", async () => {
  await vis(page.getByRole("heading", { name: "bun run dev" }))
  await side.getByText(/ingest\.py/).first().click()
  await vis(page.getByRole("group", { name: "Timeline events" }))
  const n = await page.getByRole("group", { name: "Timeline events" }).getByRole("button").count()
  if (n < 3) throw new Error("expected several markers, got " + n)
  await shot("01-overview-markers")
})
await step("marker click opens output at that time", async () => {
  await page.getByRole("group", { name: "Timeline events" }).getByRole("button", { name: /^stderr at/ }).first().click()
  await vis(page.getByText(/^Output at T\+/))
  await shot("02-output-jump")
})
await step("chart click jumps; drag zooms", async () => {
  await page.getByRole("tab", { name: "Overview" }).click()
  const box = await main.locator(".recharts-wrapper").first().boundingBox()
  await page.mouse.move(box.x + box.width * 0.3, box.y + 120); await page.waitForTimeout(100)
  await page.mouse.down(); await page.mouse.move(box.x + box.width * 0.6, box.y + 120, { steps: 6 }); await page.waitForTimeout(100); await page.mouse.up()
  await vis(page.getByRole("button", { name: /–/ }))
  if (await page.getByRole("tab", { name: /Output/ }).getAttribute("data-state") === "active") throw new Error("drag jumped to output")
  await page.getByRole("button", { name: /–/ }).first().click()
  const b2 = await main.locator(".recharts-wrapper").first().boundingBox()
  await page.mouse.move(b2.x + b2.width * 0.5, b2.y + 120); await page.waitForTimeout(100)
  await page.mouse.down(); await page.mouse.up()
  await page.waitForFunction(() => document.querySelector('[role=tab][data-state=active]')?.textContent?.startsWith("Output"), null, { timeout: 5000 })
})
await step("report tab + copies", async () => {
  await page.getByRole("tab", { name: "Report" }).click()
  await vis(page.getByRole("heading", { name: "Failed." }))
  await page.getByRole("button", { name: "Copy Markdown" }).click()
  const md = await page.evaluate(() => navigator.clipboard.readText())
  if (!md.includes("# Peak run report") || !md.includes("## Alerts") || !md.includes("Memory reached")) throw new Error("markdown missing content")
  await page.getByRole("button", { name: "Copy JSON" }).click()
  await page.waitForTimeout(100)
  const j = JSON.parse(await page.evaluate(() => navigator.clipboard.readText()))
  if (j.state !== "failed" || !j.alerts.length) throw new Error("json missing content")
  await shot("03-report")
})
await step("resources tab", async () => {
  await side.getByText("python train.py").first().click()
  await page.getByRole("tab", { name: /Resources/ }).click()
  for (const t of ["Memory by process.", "Threads and handles.", "Runtime lag.", "Listening ports."]) await vis(page.getByRole("heading", { name: t }))
  await page.waitForTimeout(300); await shot("04-resources")
})
await step("cpu profile records with progress and shows time values", async () => {
  await page.getByRole("tab", { name: /Profiler/ }).click()
  await page.getByRole("radio", { name: "CPU" }).click()
  await page.getByRole("button", { name: "Record 5s" }).click()
  await vis(page.getByRole("status"))
  await page.waitForTimeout(1500); await shot("05-cpu-recording")
  await vis(page.getByText(/lock waits are included/).or(page.getByText(/Sampled by V8/)))
  await page.getByRole("heading", { name: "CPU profile." }).waitFor({ timeout: 7000 })
  await page.locator("button.absolute").nth(2).hover(); await page.waitForTimeout(800)
  const hover = await main.textContent()
  if (!/\d+(\.\d+)?(ms|s) total/.test(hover)) throw new Error("flame hover not in time units")
  await shot("06-cpu-profile")
})
await step("machine strip and page", async () => {
  await side.getByRole("button", { name: /This machine/ }).click()
  await vis(page.getByRole("heading", { name: "This machine." }))
  await page.waitForTimeout(300); await shot("07-machine")
})
await step("history search, compare leaves session alone", async () => {
  const before = await side.locator("li").count()
  await side.getByRole("button", { name: "History" }).click()
  await vis(page.getByRole("heading", { name: "History." }))
  await shot("08-history")
  await page.getByRole("textbox", { name: "Search history" }).fill("npm test")
  await page.waitForTimeout(200)
  const boxes = main.getByRole("checkbox")
  if (await boxes.count() !== 2) throw new Error("search should leave 2 runs, got " + await boxes.count())
  await boxes.nth(0).check(); await boxes.nth(1).check()
  await page.getByRole("button", { name: "Compare" }).click()
  await vis(page.getByRole("heading", { name: "Differences." }))
  await page.waitForTimeout(300); await shot("09-compare")
  if (await side.locator("li").count() !== before) throw new Error("compare changed the session")
})
await step("reopen stored run is marked", async () => {
  await main.getByRole("button", { name: "History" }).click()
  await page.getByRole("textbox", { name: "Search history" }).fill("2026-09")
  await page.waitForTimeout(200)
  await main.getByRole("button", { name: /^Open / }).click()
  await vis(page.getByText(/^From history ·/))
  await vis(side.getByText("From history"))
  await shot("10-reopened")
})
await step("settings persist across reload, storage updates, alert fires", async () => {
  await side.getByRole("button", { name: "Settings" }).click()
  await vis(page.getByRole("heading", { name: "Settings." }))
  await page.getByRole("radio", { name: "Dark theme" }).click()
  await page.getByRole("textbox", { name: "Memory threshold in MiB" }).fill("1")
  await page.getByRole("button", { name: "Save settings" }).click()
  await vis(page.getByText("Settings saved"))
  await vis(page.getByText(/^Alert: /))
  await shot("11-settings-dark-alert")
  const before = await page.getByText(/stopped\)$/).textContent()
  await page.getByRole("button", { name: "Delete all stopped runs" }).click()
  await page.getByRole("button", { name: "Delete all" }).click()
  await vis(page.getByText(/^Removed \d+ runs/))
  await page.waitForFunction((b) => [...document.querySelectorAll("span")].some((e) => /\(0 stopped\)$/.test(e.textContent)) , before, { timeout: 4000 })
  await page.reload()
  await side.getByRole("button", { name: "Settings" }).click()
  const v = await page.getByRole("textbox", { name: "Memory threshold in MiB" }).inputValue()
  if (v !== "1") throw new Error("settings didn't survive reload: " + v)
  if (!(await page.evaluate(() => document.documentElement.classList.contains("dark")))) throw new Error("theme didn't survive")
  await page.getByRole("button", { name: "Close" }).click()
  await page.waitForTimeout(400); await shot("12-dark-overview")
})
await step("simulated target: connect, attach, lose the link, reconnect", async () => {
  await side.getByRole("button", { name: "Targets" }).click()
  await vis(page.getByRole("heading", { name: "Targets." }))
  const card = page.getByRole("region", { name: /staging-1/ })
  await card.getByRole("button", { name: "Connect" }).click()
  await vis(card.getByText("Connected"))
  await vis(card.getByText("Host memory"))
  await shot("13-targets")
  await page.getByRole("radio", { name: "Docker" }).click()
  await main.getByRole("button", { name: /shop-web/ }).click()
  await vis(page.getByText(/The whole container, not one process tree/))
  await vis(page.getByText(/These PIDs differ/))
  await page.waitForTimeout(200); await shot("14-docker-browser")
  await page.getByRole("radio", { name: "Kubernetes" }).click()
  await main.getByRole("button", { name: /api-7f9c.*\/ api/ }).click()
  await vis(page.getByText(/no metrics API available/))
  await page.waitForTimeout(200); await shot("15-kube-browser")
  await side.getByRole("button", { name: "Capture" }).click()
  await page.getByRole("combobox", { name: "Where" }).selectOption("staging")
  await main.getByText("node server.js --port 8080").click()
  await vis(page.getByRole("heading", { name: "node server.js --port 8080" }))
  if (await page.getByRole("button", { name: "Stop", exact: true }).count()) throw new Error("attached service offers Stop")
  await vis(page.getByRole("button", { name: "Detach" }))
  await page.waitForTimeout(1200)
  await side.getByRole("button", { name: "Targets" }).click()
  const card2 = page.getByRole("region", { name: /staging-1/ })
  await card2.getByRole("button", { name: "Disconnect" }).click()
  await side.getByText("node server.js --port 8080").first().click()
  await vis(page.getByText(/It may still be running/))
  await vis(side.getByLabel("No connection"))
  await shot("16-connection-lost")
  await page.waitForTimeout(2000)
  await side.getByRole("button", { name: "Targets" }).click()
  await page.getByRole("region", { name: /staging-1/ }).getByRole("button", { name: "Connect" }).click()
  await vis(page.getByRole("region", { name: /staging-1/ }).getByText("Connected"))
  await side.getByText("node server.js --port 8080").first().click()
  await vis(page.getByText("No data").first())
  await page.waitForTimeout(800); await shot("17-gap-after-reconnect")
})
await browser.close()
console.log(problems.length ? "PROBLEMS:\n" + problems.join("\n") : "ALL OK")
process.exit(problems.length ? 1 : 0)
