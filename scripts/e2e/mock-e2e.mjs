  const blank = await page.evaluate(() => new Promise((res) => { let n = 0; const t0 = performance.now(); const f = () => { if (!document.querySelector("main .recharts-tooltip-wrapper")?.textContent) n++; performance.now() - t0 > 1500 ? res(n) : requestAnimationFrame(f) }; requestAnimationFrame(f) }))
  if (blank) throw new Error("tooltip flickered on a stored run: " + blank)
