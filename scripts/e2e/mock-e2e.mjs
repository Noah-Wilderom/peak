  const over = await main.evaluate((m) => { const r = m.getBoundingClientRect(); return [...m.querySelectorAll('[role=radiogroup]')].some((g) => g.getBoundingClientRect().right > r.right + 1) || m.scrollWidth > m.clientWidth + 1 })
